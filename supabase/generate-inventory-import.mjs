// Generates a reviewable owner-only SQL import. Does not connect to any service.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

const snapshot = JSON.parse(readFileSync(process.argv[2] ?? new URL("../data/inventory-source.json", import.meta.url), "utf8"));
const document = {
  title: snapshot.source.title,
  url: snapshot.source.url,
  extracted_at_utc: snapshot.source.extracted_at_utc,
  quantity_mode: snapshot.source.quantity_mode,
};
const quote = (value) => value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const number = (value) => {
  if (value == null) return "null";
  if (typeof value !== "number" || !Number.isFinite(value)) throw new Error("Invalid numeric source value");
  return String(value);
};
const quantity = (value) => {
  if (value != null && (!Number.isSafeInteger(value) || value < 0)) throw new Error("Invalid stock quantity");
  return number(value);
};
const operationId = (sku, location) => {
  const hex = createHash("sha256").update(`luckylap-opening:${snapshot.source.download_sha256}:${sku}:${location}`).digest("hex");
  return [hex.slice(0, 8), hex.slice(8, 12), hex.slice(12, 16), hex.slice(16, 20), hex.slice(20, 32)].join("-");
};
const active = (value) => String(value).trim().toLowerCase() === "si" ? "true" : "false";
const itemId = (sku) => `(select id from public.stock_items where sku = ${quote(sku)})`;
const locationId = (code) => `(select id from public.stock_locations where code = ${quote(code)})`;
const inventory = new Map(snapshot.inventory.map((row) => [row.sku, row]));
if (inventory.size !== snapshot.inventory.length || new Set(snapshot.variants.map((row) => row.sku)).size !== snapshot.variants.length) {
  throw new Error("Duplicate SKU in snapshot");
}
if (snapshot.variants.length !== inventory.size) throw new Error("Variants and inventory do not match");

const sql = [
  "-- GENERATED by node supabase/generate-inventory-import.mjs. Review before applying as DB owner.",
  "-- Source: authorized local Excel snapshot; cached values, NOT reconciled physical counts.",
  `-- Workbook SHA-256: ${snapshot.source.download_sha256}`,
  "-- No sales, finance, packaging, Shopify or new external data. No database connection made by generator.",
  "begin;",
  "do $$ begin",
  "  if exists (select 1 from public.stock_items) or exists (select 1 from public.products)",
  "    or exists (select 1 from public.stock_locations) or exists (select 1 from public.stock_movements) then",
  "    raise exception 'Initial inventory requires an empty catalog and ledger. Reimport refused.';",
  "  end if;",
  "end $$;",
];

for (const row of snapshot.products) {
  sql.push(`insert into public.products(model, category, production_lead_days, source) values (${quote(row.model)}, ${quote(row.category)}, ${number(row.production_lead_days)}, ${json(row.source)});`);
}
for (const row of snapshot.locations) {
  sql.push(`insert into public.stock_locations(code, name, location_type, source) values (${quote(row.code)}, ${quote(row.name)}, ${quote(row.type)}, ${json(row.source)});`);
}
for (const row of snapshot.variants) {
  const stock = inventory.get(row.sku);
  if (!stock || stock.model !== row.model) throw new Error(`Inventory mismatch for ${row.sku}`);
  sql.push(`insert into public.stock_items(kind, sku, name, unit_cost_eur, list_price_eur, active, source) values ('product', ${quote(row.sku)}, ${quote(`${row.model} · ${row.color} · ${row.size}`)}, ${number(stock.unit_cost_eur)}, ${number(stock.list_price_eur)}, ${active(row.active_source_value)}, ${json({ variant: row.source, inventory: stock.source, source_hash: snapshot.source.download_sha256, document })});`);
  sql.push(`insert into public.product_variants(stock_item_id, product_id, color, size, central_target_quantity, source) values (${itemId(row.sku)}, (select id from public.products where model = ${quote(row.model)}), ${quote(row.color)}, ${quote(row.size)}, ${quantity(stock.central_target_quantity)}, ${json(row.source)});`);
  for (const location of stock.stocks) {
    if (!snapshot.locations.some((place) => place.code === location.location_code)) throw new Error("Unknown source location");
    if (location.quantity == null) {
      sql.push(`insert into public.stock_balances(stock_item_id, location_id, quantity) values (${itemId(row.sku)}, ${locationId(location.location_code)}, null);`);
    } else {
      sql.push(`insert into public.stock_movements(operation_id, stock_item_id, location_id, kind, quantity_delta, reason, source) values (${quote(operationId(row.sku, location.location_code))}, ${itemId(row.sku)}, ${locationId(location.location_code)}, 'opening', ${quantity(location.quantity)}, 'Snapshot Excel iniziale: valore salvato, conta fisica da verificare', ${json({ ...stock.source, cell: location.source_cell, source_hash: snapshot.source.download_sha256, inventory_as_of_date: snapshot.source.inventory_as_of_date })});`);
    }
  }
}
sql.push("commit;", "");
process.stdout.write(sql.join("\n"));
